"""Kometa integration: write a collection YAML and register it in config.yml."""
import json
import os
import re
from datetime import date

from .. import config


def _slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "list"


def create_collection(list_name: str, movies: list[dict], source_url: str = "", tmdb_list_id: str = "") -> str:
    tmdb_ids = [m["tmdb_id"] for m in movies if m.get("tmdb_id")]
    if not tmdb_ids and not tmdb_list_id:
        raise RuntimeError("No movies with a TMDB id to add.")

    slug = _slug(list_name)
    filename = f"collecta-{slug}.yml"
    abs_path = os.path.join(config.KOMETA_CONFIG_DIR, filename)
    rel_path = f"config/{filename}"

    if tmdb_list_id:
        # Single builder: reads the shared TMDB list (also used by Radarr), order preserved.
        builder = f"    tmdb_list: {tmdb_list_id}\n    collection_order: custom\n"
        count = len(tmdb_ids) or "list"
    else:
        ids_csv = ", ".join(str(i) for i in tmdb_ids)
        builder = f"    tmdb_movie: {ids_csv}\n"
        count = len(tmdb_ids)
    # Pasted-text sources can be multi-line; collapse to one line so it stays a valid comment.
    source_line = " ".join((source_url or "n/a").split())[:200]
    content = (
        f"# Generated by Collecta on {date.today().isoformat()}\n"
        f"# Source: {source_line}\n"
        "collections:\n"
        # Double-quote the key: unquoted names with a colon (e.g. "Title: Subtitle") break the YAML mapping.
        f"  {json.dumps(list_name)}:\n"
        f"{builder}"
        "    sync_mode: sync\n"
        # Pin to Plex Home, other users' Home, and the library Recommended tab.
        "    visible_home: true\n"
        "    visible_shared: true\n"
        "    visible_library: true\n"
    )
    with open(abs_path, "w", encoding="utf-8") as fh:
        fh.write(content)

    registered = _register_in_config(rel_path)
    note = "registered in config.yml" if registered else "already registered in config.yml"
    src = f"TMDB list {tmdb_list_id}" if tmdb_list_id else f"{count} movies"
    return f"Wrote Kometa collection '{list_name}' ({src}) to {rel_path}; {note}."


def trigger_run(list_name: str) -> str:
    """Kick off a Kometa run limited to this collection's file (detached; runs take minutes)."""
    run_files = f"collecta-{_slug(list_name)}"
    try:
        import docker

        client = docker.from_env()
        container = client.containers.get(config.KOMETA_CONTAINER)
        container.exec_run(
            ["python3", "kometa.py", "--run", "--run-files", run_files], detach=True
        )
        return f"Triggered Kometa run for {run_files}.yml."
    except Exception as exc:  # noqa: BLE001
        return f"Could not trigger Kometa run automatically: {exc}"


def _register_in_config(rel_path: str) -> bool:
    config_path = os.path.join(config.KOMETA_CONFIG_DIR, "config.yml")
    with open(config_path, encoding="utf-8") as fh:
        lines = fh.readlines()

    if any(rel_path in ln for ln in lines):
        return False

    start = None
    for i, ln in enumerate(lines):
        if re.match(rf"^  {re.escape(config.KOMETA_LIBRARY)}:(\s|$)", ln):
            start = i
            break
    if start is None:
        raise RuntimeError(f"Library '{config.KOMETA_LIBRARY}' not found in config.yml.")

    end = len(lines)
    for j in range(start + 1, len(lines)):
        if re.match(r"^  \S", lines[j]) and not lines[j].startswith("   "):
            end = j
            break

    insert_at = None
    for j in range(start, end):
        if lines[j].strip().startswith("- file:"):
            insert_at = j + 1
    if insert_at is None:
        for j in range(start, end):
            if lines[j].strip() == "collection_files:":
                insert_at = j + 1
                break
    if insert_at is None:
        raise RuntimeError("Could not find a collection_files list to register into.")

    lines.insert(insert_at, f"    - file: {rel_path}\n")
    with open(config_path, "w", encoding="utf-8") as fh:
        fh.writelines(lines)
    return True
